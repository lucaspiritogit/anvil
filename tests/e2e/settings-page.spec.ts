  await page.getByLabel('Embedding model', { exact: true }).fill('  custom-embedding-model  ')
  await page.getByLabel('Ollama base URL', { exact: true }).fill('  http://127.0.0.1:11434/v1  ')
  await expect(page.getByText('Saved', { exact: true })).toBeVisible()
