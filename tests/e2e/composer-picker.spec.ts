test('unavailable catalogues preserve the saved model and allow custom models without an implicit default', async ({ page }) => {
  await page.goto(fixture)
  await page.evaluate(() => {
    window.anvil.agents.models = async (agentId) => ({ agentId, models: [], error: 'Provider unavailable' })
  })
  const composer = page.getByRole('form', { name: 'Start a task' })
  await chooseProvider(composer.getByRole('button', { name: /^(Choose a model|Model:)/ }), 'opencode')
  await composer.getByRole('button', { name: 'Model: model', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Choose model' })
  await expect(dialog.getByRole('button', { name: 'model', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(dialog.getByRole('status')).toHaveText('Could not list models: Provider unavailable')
  await dialog.getByRole('textbox', { name: 'Custom model' }).fill('openai/gpt-5.4')
  await dialog.getByRole('button', { name: 'Use custom model' }).click()
  await composer.getByRole('button', { name: 'Model: GPT 5.4', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Agent default', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'GPT 5.4', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(composer.getByRole('button', { name: 'Model: GPT 5.4', exact: true })).toBeVisible()
})

