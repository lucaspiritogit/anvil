test('rapid autosaves keep latest input and failure retry across dismissal', async ({ page }) => {
  await page.goto(`${fixture}?settingsControlled`)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const display = () => page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Display', exact: true }).click()
  await display()
  const font = page.getByLabel('Font size', { exact: true })
  await font.selectOption('18')
  await font.selectOption('12')
  await expect.poll(() => page.evaluate(() => window.settingsTest.calls.length)).toBe(1)
  await page.evaluate(() => window.settingsTest.release())
  await expect.poll(() => page.evaluate(() => window.settingsTest.calls.length)).toBe(2)
  await expect(font).toHaveValue('12')
  await expect(page.getByText('Saving settings…', { exact: true })).toBeVisible()
  await expect(page.getByText('Saved', { exact: true })).toBeHidden()
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.settingsTest.release(true))
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await display()
  await expect(font).toHaveValue('12')
  await expect(page.getByRole('alert')).toContainText('Could not save settings')
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.settingsTest.calls.length)).toBe(3)
  await page.evaluate(() => window.settingsTest.release())
  await expect(page.getByText('Saved', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.settingsTest.calls)).toEqual([{ fontSize: 18 }, { fontSize: 12 }, { fontSize: 12 }])
})

