test('late provider results stay in their own list and long catalogues scroll beside the provider column', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 600, height: 480 })
  await page.goto(fixture)
  await page.evaluate(() => {
    const originalModels = window.anvil.agents.models
    window.anvil.agents.models = async (agentId) => {
      if (agentId !== 'opencode') return originalModels(agentId)
      await new Promise<void>((resolve) => window.addEventListener('fixture:models-ready', () => resolve(), { once: true }))
      return { agentId, models: Array.from({ length: 100 }, (_, index) => `openrouter/company/model-${index}`) }
    }
  })
  const trigger = page.getByRole('button', { name: 'Model: GPT 5', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Choose model' })
  const providers = dialog.getByRole('navigation', { name: 'Providers' })
  const models = dialog.getByRole('group', { name: 'Models', exact: true })
  await providers.getByRole('button', { name: 'OpenCode', exact: true }).click()
  await expect(models).toHaveAttribute('aria-busy', 'true')
  await providers.getByRole('button', { name: 'Codex', exact: true }).click()
  await page.evaluate(() => window.dispatchEvent(new Event('fixture:models-ready')))
  await expect(models.getByRole('button', { name: 'GPT 5', exact: true })).toBeVisible()
  await expect(models.getByRole('button', { name: 'model-99', exact: true })).toHaveCount(0)
  await dialog.getByRole('searchbox').fill('GPT')
  await providers.getByRole('button', { name: 'OpenCode', exact: true }).click()
  await expect(dialog.getByRole('searchbox')).toHaveValue('')
  await expect(models.getByRole('button')).toHaveCount(101)
  const providerBounds = await providers.boundingBox()
  await dialog.getByRole('searchbox').press('ArrowDown')
  await page.keyboard.press('End')
  const last = models.getByRole('button').last()
  await expect(last).toBeFocused()
  await expect(last).toBeInViewport()
  expect(await models.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  expect(await providers.boundingBox()).toEqual(providerBounds)
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('unified-picker-scroll.png') })
  await page.keyboard.press('Escape')
  await expect(trigger).toHaveAccessibleDescription('Codex')
})
