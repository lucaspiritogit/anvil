test('providers stay beside scrollable models, support keyboard navigation, and cancel without changing selection', async ({ page }, testInfo) => {
  await page.goto(fixture)
  const trigger = page.getByRole('button', { name: 'Model: GPT 5', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Choose model', exact: true })
  const search = dialog.getByRole('searchbox', { name: 'Search models' })
  const providers = dialog.getByRole('navigation', { name: 'Providers' })
  const codex = providers.getByRole('button', { name: 'Codex', exact: true })
  const opencode = providers.getByRole('button', { name: 'OpenCode', exact: true })
  await expect(search).toBeFocused()
  await expect(codex).toHaveAttribute('aria-pressed', 'true')
  await codex.focus()
  await codex.press('ArrowDown')
  await expect(opencode).toBeFocused()
  await opencode.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(opencode).toHaveAttribute('aria-pressed', 'true')
  const list = dialog.getByRole('group', { name: 'Models', exact: true })
  await expect(list.getByRole('button', { name: 'model', exact: true })).toBeVisible()
  const left = (await providers.boundingBox())!
  expect((await list.boundingBox())!.x).toBeGreaterThanOrEqual(left.x + left.width)
  await opencode.press('ArrowRight')
  await expect(search).toBeFocused()
  await search.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(dialog).toHaveCount(0)
  const selected = page.getByRole('button', { name: 'Model: model', exact: true })
  await expect(selected).toHaveAccessibleDescription('OpenCode')
  await expect(selected).toBeFocused()
  await selected.click()
  await codex.click()
  await page.screenshot({ path: testInfo.outputPath('unified-picker-wide.png') })
  await page.mouse.click(5, 5)
  await expect(dialog).toHaveCount(0)
  await expect(selected).toHaveAccessibleDescription('OpenCode')
  await expect(selected).toBeFocused()
})

